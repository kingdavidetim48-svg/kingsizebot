/**
 * Verifies the bots table exists with the expected columns and constraints, and
 * round-trips a row through Drizzle to confirm the schema matches the database.
 * Cleans up the test row it creates.
 *
 * Usage: npx tsx scripts/check-schema.ts
 */
import { config } from "dotenv"

config({ path: ".env.local" })

import { eq } from "drizzle-orm"

import { bots, db } from "../lib/db"

const USER_ID = "user_check_roundtrip"
const NAME = "Round-trip check"

async function main() {
  const columns = await db.execute(`
    select column_name, data_type, is_nullable, column_default
    from information_schema.columns
    where table_schema = 'public' and table_name = 'bots'
    order by ordinal_position
  `)

  console.log("bots columns:")
  for (const row of columns.rows) {
    const r = row as Record<string, unknown>
    console.log(
      `  ${r.column_name} (${r.data_type}) nullable=${r.is_nullable} default=${r.column_default ?? "-"}`
    )
  }

  const constraints = await db.execute(`
    select tc.constraint_name, tc.constraint_type
    from information_schema.table_constraints tc
    where tc.table_schema = 'public' and tc.table_name = 'bots'
    order by tc.constraint_name
  `)

  console.log("\nbots constraints:")
  for (const row of constraints.rows) {
    const r = row as Record<string, unknown>
    console.log(`  ${r.constraint_name} (${r.constraint_type})`)
  }

  const indexes = await db.execute(`
    select indexname, indexdef
    from pg_indexes
    where schemaname = 'public' and tablename = 'bots'
    order by indexname
  `)

  console.log("\nbots indexes:")
  for (const row of indexes.rows) {
    const r = row as Record<string, unknown>
    console.log(`  ${r.indexname}: ${r.indexdef}`)
  }

  // id and avatar are generated by the schema's nanoid defaults.
  const inserted = await db
    .insert(bots)
    .values({ userId: USER_ID, name: NAME, job: "verify the schema" })
    .returning()

  console.log("\ninserted:", inserted[0])

  if (inserted[0].id === inserted[0].avatar) {
    throw new Error("id and avatar should be generated independently")
  }
  if (!inserted[0].id || !inserted[0].avatar) {
    throw new Error("id and avatar should both be populated")
  }

  const fetched = await db.select().from(bots).where(eq(bots.name, NAME))
  console.log("fetched: ", fetched[0])

  await db.delete(bots).where(eq(bots.name, NAME))
  console.log("\ncleaned up test row")
}

main().catch((err) => {
  console.error("Schema check failed:", err)
  process.exit(1)
})
